export function getPillarComponents(pillar) {
  return {
    stem: pillar[0],
    branch: pillar[1],
    stemData: HEAVENLY_STEMS[pillar[0]],
    branchData: EARTHLY_BRANCHES[pillar[1]]
  };
}

export function formatPillar(pillar) {
  const { stem, branch, stemData, branchData } = getPillarComponents(pillar);
  return {
    chinese: `${stem}${branch}`,
    english: `${stemData.english} ${branchData.animal}`,
    pinyin: `${stemData.pinyin} ${branchData.pinyin}`,
    element: `${stemData.element} on ${branchData.element}`
  };
}

