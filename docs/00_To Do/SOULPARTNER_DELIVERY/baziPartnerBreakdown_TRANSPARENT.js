    step: 4,
    action: 'Find 6 Harmony partner branch',
    input: `Your branch: ${branch} (${branchData.animal})`,
    formula: `SIX_HARMONIES[${branch}] = ${harmonyBranch || 'None'}`,
    result: harmonyBranch ? `${harmonyBranch} (${harmonyBranchData.animal})` : 'No direct harmony',
    reasoning: harmonyBranch 
