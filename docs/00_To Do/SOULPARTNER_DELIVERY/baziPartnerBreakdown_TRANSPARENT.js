function calculateTotalScore(breakdown) {
  const total = 
    breakdown.day.weightedScore +
    breakdown.hour.weightedScore +
    breakdown.month.weightedScore +
    breakdown.year.weightedScore;
  
  // SHOW CALCULATION STEPS
  const calculationSteps = [
    {
      step: 1,
      component: 'Day Pillar',
      formula: `${breakdown.day.score} × ${breakdown.day.weight}% = ${breakdown.day.weightedScore} pts`,
      result: breakdown.day.weightedScore
    },
    {
      step: 2,
      component: 'Hour Pillar',
      formula: `${breakdown.hour.score} × ${breakdown.hour.weight}% = ${breakdown.hour.weightedScore} pts`,
      result: breakdown.hour.weightedScore
    },
    {
      step: 3,
      component: 'Month Pillar',
      formula: `${breakdown.month.score} × ${breakdown.month.weight}% = ${breakdown.month.weightedScore} pts`,
      result: breakdown.month.weightedScore
    },
    {
      step: 4,
      component: 'Year Pillar',
      formula: `${breakdown.year.score} × ${breakdown.year.weight}% = ${breakdown.year.weightedScore} pts`,
      result: breakdown.year.weightedScore
    },
    {
      step: 5,
      component: 'TOTAL',
      formula: `${breakdown.day.weightedScore} + ${breakdown.hour.weightedScore} + ${breakdown.month.weightedScore} + ${breakdown.year.weightedScore} = ${total} pts`,
      result: total
    }
  ];
  
  let tier, icon, description;
  if (total >= 95) {
    tier = 'Perfect'; icon = '💎'; description = 'Soul Twin - Rare cosmic alignment';
  } else if (total >= 90) {
    tier = 'Exceptional'; icon = '🏆'; description = 'AI SoulPartner - Deep match';
  } else if (total >= 85) {
    tier = 'Excellent'; icon = '⭐'; description = 'Strong compatibility';
  } else if (total >= 80) {
    tier = 'Very Good'; icon = '✨'; description = 'Good foundation';
  } else if (total >= 70) {
    tier = 'Good'; icon = '○'; description = 'Compatible with effort';
  } else {
    tier = 'Moderate'; icon = '△'; description = 'Challenging';
  }
  
  return {
    total: Math.round(total * 10) / 10,
    breakdown: {
      day: breakdown.day.weightedScore,
      hour: breakdown.hour.weightedScore,
      month: breakdown.month.weightedScore,
      year: breakdown.year.weightedScore
    },
    tier,
    icon,
    description,
    
    // CALCULATION TRANSPARENCY
    calculation: {
      steps: calculationSteps,
      formula: 'Sum of all weighted pillar scores',
      componentBreakdown: {
        day: { base: breakdown.day.score, weight: breakdown.day.weight, weighted: breakdown.day.weightedScore },
        hour: { base: breakdown.hour.score, weight: breakdown.hour.weight, weighted: breakdown.hour.weightedScore },
        month: { base: breakdown.month.score, weight: breakdown.month.weight, weighted: breakdown.month.weightedScore },
        year: { base: breakdown.year.score, weight: breakdown.year.weight, weighted: breakdown.year.weightedScore }
      }
    }
  };
}

