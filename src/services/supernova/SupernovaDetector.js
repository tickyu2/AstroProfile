/**
 * Get detailed analysis for a specific detector
 */
export function getDetectorAnalysis(detectorName, archetypeA, archetypeB) {
  const detectorMap = {
    competingDominance: detectCompetingDominance,
    softBoundaryEmpath: detectSoftBoundaryEmpath,
    rigidMoralist: detectRigidMoralist,
    fragileIdealist: detectFragileIdealist
  };

  const detector = detectorMap[detectorName];
  if (!detector) {
    return { error: `Unknown detector: ${detectorName}` };
  }

  return detector(archetypeA, archetypeB);
}

