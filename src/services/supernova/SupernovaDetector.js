// Grade order for cap comparisons (lower index = worse grade)
const GRADE_ORDER = ['F', 'D-', 'D', 'D+', 'C-', 'C', 'C+', 'B-', 'B', 'B+', 'A-', 'A', 'A+'];

/**
 * Choose the stricter (lower) grade cap
 */
function capGrade(existing, incoming) {
  if (!existing) return incoming;
  if (!incoming) return existing;

  const existingIdx = GRADE_ORDER.indexOf(existing);
  const incomingIdx = GRADE_ORDER.indexOf(incoming);

  // Lower index = worse grade = stricter cap
  return existingIdx <= incomingIdx ? existing : incoming;
}

