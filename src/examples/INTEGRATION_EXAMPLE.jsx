// EXAMPLE 5: Custom Hook Pattern
// ═══════════════════════════════════════════════════════

export function useCompatibilityInsights(typeA, typeB) {
  const [insights, setInsights] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [fromCache, setFromCache] = useState(false);

  useEffect(() => {
    let cancelled = false;

    async function load() {
      if (!typeA || !typeB) {
        setLoading(false);
        return;
      }

      setLoading(true);
      setError(null);

      try {
        const result = await getCompatibilityInsights(typeA, typeB);
        
        if (!cancelled) {
          setInsights(result.insights);
          setFromCache(result.fromCache);
          setLoading(false);
        }
      } catch (err) {
        if (!cancelled) {
          setError(err);
          setLoading(false);
        }
      }
    }

    load();

    return () => {
      cancelled = true;
    };
  }, [typeA, typeB]);

  return { insights, loading, error, fromCache };
}

