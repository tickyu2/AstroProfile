import React, { useState, useEffect } from 'react';
import { getCompatibilityInsights } from '../services/mbtiCompatibilityAI';

// ═══════════════════════════════════════════════════════
// EXAMPLE 1: Simple Component Usage
// ═══════════════════════════════════════════════════════

export function SimpleCompatibilityView({ typeA, typeB }) {
  const [insights, setInsights] = useState(null);
  const [loading, setLoading] = useState(true);
  const [fromCache, setFromCache] = useState(false);

  useEffect(() => {
    async function loadInsights() {
      setLoading(true);
      
      try {
        const result = await getCompatibilityInsights(typeA, typeB);
        setInsights(result.insights);
        setFromCache(result.fromCache);
      } catch (error) {
        console.error('Error loading insights:', error);
      }
      
      setLoading(false);
    }

    if (typeA && typeB) {
      loadInsights();
    }
  }, [typeA, typeB]);

  if (loading) {
    return <div>Analyzing compatibility...</div>;
  }

  if (!insights) {
    return <div>Unable to load compatibility analysis</div>;
  }

  return (
    <div>
      {/* Cache indicator */}
      <div className="text-sm text-gray-500 mb-4">
        {fromCache ? '⚡ Loaded from cache' : '🤖 Generated by AI'}
      </div>

      {/* Overall score */}
      <div className="text-4xl font-bold mb-4">
        {insights.overallCompatibility}% Compatible
      </div>

      {/* Strengths */}
      <div className="mb-6">
        <h3 className="font-bold mb-2">💪 Strengths</h3>
        <ul>
          {insights.analysis.strengths.map((strength, i) => (
            <li key={i}>{strength}</li>
          ))}
        </ul>
      </div>

      {/* Challenges */}
      <div className="mb-6">
        <h3 className="font-bold mb-2">⚠️ Challenges</h3>
        <ul>
          {insights.analysis.challenges.map((challenge, i) => (
            <li key={i}>{challenge}</li>
          ))}
        </ul>
      </div>

      {/* Metaphor */}
      <div className="bg-purple-100 p-4 rounded-lg">
        <h3 className="font-bold mb-2">{insights.metaphor.title}</h3>
        <p>{insights.metaphor.description}</p>
      </div>
    </div>
  );
}

