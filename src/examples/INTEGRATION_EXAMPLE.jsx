// EXAMPLE 3: Preloading for Performance
// ═══════════════════════════════════════════════════════

export function MBTIRoseWindowWithPreload({ currentType }) {
  const [preloadedTypes] = useState([
    'ISTJ', 'ISFJ', 'INFJ', 'INTJ',
    'ISTP', 'ISFP', 'INFP', 'INTP'
  ]);

  useEffect(() => {
    // Preload common type combinations in the background
    async function preload() {
      if (!currentType) return;

      // Preload first 3 types silently
      for (let i = 0; i < 3; i++) {
        const partnerType = preloadedTypes[i];
        if (partnerType === currentType) continue;

        try {
          // This will cache the result for instant display later
          await getCompatibilityInsights(currentType, partnerType);
          console.log(`✓ Preloaded ${currentType}-${partnerType}`);
        } catch (error) {
          console.warn(`Failed to preload ${partnerType}:`, error);
        }

        // Small delay between preloads to avoid rate limits
        await new Promise(resolve => setTimeout(resolve, 1000));
      }
    }

    preload();
  }, [currentType]);

  return (
    <div>
      {/* Your existing MBTIRoseWindow component */}
      {/* When user clicks a portal, insights load instantly from cache */}
    </div>
  );
}

