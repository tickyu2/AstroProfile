// HELPER FUNCTIONS
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Get a script by stage ID
 * @param {String} stageId - The individuation stage ID
 * @returns {Object|null} - The script or null if not found
 */
export function getScript(stageId) {
  return PILGRIM_JOURNEY_SCRIPTS[stageId] || null;
}

/**
 * Get all script stage IDs
 * @returns {Array} - Array of stage IDs
 */
export function getAllScriptIds() {
  return Object.keys(PILGRIM_JOURNEY_SCRIPTS);
}

/**
 * Get a specific section from a script
 * @param {String} stageId - The individuation stage ID
 * @param {String} sectionTitle - The section title (e.g., "Threshold Invocation")
 * @returns {Object|null} - The section or null if not found
 */
export function getScriptSection(stageId, sectionTitle) {
  const script = PILGRIM_JOURNEY_SCRIPTS[stageId];
  if (!script) return null;
  return script.sections.find(s => s.title === sectionTitle) || null;
}

/**
 * Generate a voice script for persona layer
 * @param {String} stageId - The individuation stage ID
 * @returns {String} - Voice narrative
 */
export function generateIndividuationVoice(stageId) {
  const script = PILGRIM_JOURNEY_SCRIPTS[stageId];
  if (!script) return "";

  return `You now walk the ${script.label} path.
The ${script.subtitle} awaits you.
This chamber teaches you: ${script.sections.find(s => s.title === "Trial / Task")?.text || ""}
${script.sections.find(s => s.title === "Closing Benediction")?.text || ""}`;
}

export default PILGRIM_JOURNEY_SCRIPTS;
