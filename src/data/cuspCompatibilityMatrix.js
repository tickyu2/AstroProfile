/**
 * Get compatibility score: how archetype A feels about archetype B
 * @param {number} fromIndex - Row index (0-35)
 * @param {number} toIndex - Column index (0-35)
 * @returns {number} Score 0-100
 */
export function getDirectionalScore(fromIndex, toIndex) {
  return COMPATIBILITY_MATRIX[fromIndex]?.[toIndex] ?? 50;
}

/**
 * Get mutual compatibility (average of both directions)
 */
export function getMutualScore(indexA, indexB) {
  const ab = getDirectionalScore(indexA, indexB);
  const ba = getDirectionalScore(indexB, indexA);
  return (ab + ba) / 2;
}

/**
 * Get the directional difference (how asymmetric the relationship is)
 */
export function getDirectionalDifference(indexA, indexB) {
  return Math.abs(getDirectionalScore(indexA, indexB) - getDirectionalScore(indexB, indexA));
}
