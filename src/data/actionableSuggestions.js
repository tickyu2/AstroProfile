/**
 * Get actionable suggestions for a specific Personal Year
 * @param {number} personalYear - Personal Year number (1-9)
 * @returns {Object|null} Actions for that year
 */
export function getPersonalYearActions(personalYear) {
  return personalYearActions[personalYear] || null;
}

/**
 * Get the best focus area for current timing
 * @param {number} personalYear - Personal Year
 * @param {string} area - 'career' | 'relationships' | 'health' | 'personalGrowth'
 * @returns {Object|null} Actions for that area
 */
export function getActionsByArea(personalYear, area) {
  const yearData = personalYearActions[personalYear];
  if (!yearData) return null;
  return yearData[area] || null;
}

/**
 * Get monthly check-in questions for a Personal Year
 * @param {number} personalYear - Personal Year number
 * @returns {Array} Check-in questions
 */
export function getMonthlyCheckin(personalYear) {
  const yearData = personalYearActions[personalYear];
  return yearData?.monthlyCheckin || [];
}

/**
 * Get what to avoid for a Personal Year
 * @param {number} personalYear - Personal Year number
 * @returns {Array} Things to avoid
 */
export function getWhatToAvoid(personalYear) {
  const yearData = personalYearActions[personalYear];
  return yearData?.avoid || [];
}

export default {
  personalYearActions,
  getPersonalYearActions,
  getActionsByArea,
  getMonthlyCheckin,
  getWhatToAvoid
};
