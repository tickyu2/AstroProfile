export function getDeepYinYangKnowledge(polarity) {
  return deepYinYangKnowledge[polarity] || null;
}

export function getElementComparison(yourElement, compareElement) {
  const knowledge = deepElementKnowledge[yourElement];
  if (!knowledge || !knowledge.comparison || !knowledge.comparison[compareElement]) {
    return null;
  }
  return {
    yourElement,
    compareElement,
    comparison: knowledge.comparison[compareElement]
  };
}

