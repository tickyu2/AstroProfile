/**
 * Calculate similarity score between user constitution and pattern
 * @param {Object} userConstitution - User's constitutional data
 * @param {Object} pattern - Pattern to compare against
 * @returns {number} Similarity score (0-100)
 */
export function calculateSimilarityScore(userConstitution, pattern) {
  let score = 0;
  const maxScore = 12; // Maximum possible score

  // Element match (weighted by Five Elements relationships)
  if (userConstitution.element && pattern.constitution.element) {
    score += getElementScore(userConstitution.element, pattern.constitution.element);
  }

  // Animal match (exact = 3 points)
  if (userConstitution.animal === pattern.constitution.animal) {
    score += 3;
  }

  // MBTI match (exact = 3, partial functions = 1-2)
  if (userConstitution.mbti && pattern.constitution.mbti) {
    if (userConstitution.mbti === pattern.constitution.mbti) {
      score += 3;
    } else {
      // Count matching letters
      const matches = [...userConstitution.mbti].filter((letter, i) =>
        letter === pattern.constitution.mbti[i]
      ).length;
      score += matches * 0.5;
    }
  }

  // Western zodiac match (exact = 3, same element = 1)
  if (userConstitution.western === pattern.constitution.western) {
    score += 3;
  } else if (userConstitution.western && pattern.constitution.western) {
    // Check if same zodiac element (Fire, Earth, Air, Water signs)
    const zodiacElements = {
      Fire: ['Aries', 'Leo', 'Sagittarius'],
      Earth: ['Taurus', 'Virgo', 'Capricorn'],
      Air: ['Gemini', 'Libra', 'Aquarius'],
      Water: ['Cancer', 'Scorpio', 'Pisces']
    };
    for (const [element, signs] of Object.entries(zodiacElements)) {
      if (signs.includes(userConstitution.western) && signs.includes(pattern.constitution.western)) {
        score += 1;
        break;
      }
    }
  }

  return Math.round((score / maxScore) * 100);
}

/**
 * Find most similar patterns for a user's constitution
 * @param {Object} userConstitution - User's constitutional data { element, animal, mbti, western }
 * @param {number} limit - Maximum number of patterns to return (default: 3)
 * @returns {Array} Sorted array of { pattern, score } objects
 */
export function findSimilarPatterns(userConstitution, limit = 3) {
  const scored = allPatterns.map(pattern => ({
    pattern,
    score: calculateSimilarityScore(userConstitution, pattern)
  }));

  // Sort by score descending
  scored.sort((a, b) => b.score - a.score);

  return scored.slice(0, limit);
}

/**
 * Get all patterns as context for Claude API
 * Returns condensed wisdom from all patterns for context injection
 * @returns {string} Combined pattern wisdom
 */
export function getAllPatternsContext() {
  return allPatterns.map(p =>
    `=== ${p.archetype} (${p.constitution.element} ${p.constitution.animal} ${p.constitution.mbti} ${p.constitution.western}) ===\n${p.coreWisdom}`
  ).join('\n\n');
}

/**
 * Get relevant pattern context for a user's constitution
 * Returns the most similar pattern's wisdom plus general insights
 * @param {Object} userConstitution - User's constitutional data
 * @returns {Object} { similarPatterns, context }
 */
export function getRelevantPatternContext(userConstitution) {
  const similarPatterns = findSimilarPatterns(userConstitution, 2);

  const context = similarPatterns.map(({ pattern, score }) =>
    `[${score}% match - ${pattern.archetype}]\n${pattern.coreWisdom}`
  ).join('\n\n---\n\n');

  return {
    similarPatterns,
    context
  };
}

