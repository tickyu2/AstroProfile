/**
 * Element mapping for Five Elements system
 */
const ELEMENT_WEIGHTS = {
  same: 3,      // Exact element match
  generating: 2, // Element generates or is generated by
  neutral: 1,   // No relationship
  controlling: 0 // Element controls or is controlled by
};

// Five Elements cycle relationships
const ELEMENT_RELATIONSHIPS = {
  Wood: { generates: 'Fire', generatedBy: 'Water', controls: 'Earth', controlledBy: 'Metal' },
  Fire: { generates: 'Earth', generatedBy: 'Wood', controls: 'Metal', controlledBy: 'Water' },
  Earth: { generates: 'Metal', generatedBy: 'Fire', controls: 'Water', controlledBy: 'Wood' },
  Metal: { generates: 'Water', generatedBy: 'Earth', controls: 'Wood', controlledBy: 'Fire' },
  Water: { generates: 'Wood', generatedBy: 'Metal', controls: 'Fire', controlledBy: 'Earth' }
};

/**
 * Calculate element relationship score
 */
function getElementScore(userElement, patternElement) {
  if (userElement === patternElement) return ELEMENT_WEIGHTS.same;

  const relationships = ELEMENT_RELATIONSHIPS[userElement];
  if (!relationships) return ELEMENT_WEIGHTS.neutral;

  if (relationships.generates === patternElement || relationships.generatedBy === patternElement) {
    return ELEMENT_WEIGHTS.generating;
  }
  if (relationships.controls === patternElement || relationships.controlledBy === patternElement) {
    return ELEMENT_WEIGHTS.controlling;
  }
  return ELEMENT_WEIGHTS.neutral;
}

