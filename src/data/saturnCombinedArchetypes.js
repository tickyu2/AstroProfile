/**
 * Get the combined archetype title for sign + house
 * @param {string} sign - Zodiac sign
 * @param {number} house - House number (1-12)
 * @returns {string} Archetype title
 */
export function getSaturnArchetype(sign, house) {
  const key = `${sign}_${house}`;
  return SATURN_COMBINED_ARCHETYPES[key] || "The Bearer of Saturn's Work";
}

/**
 * Get the mythic chamber title for sign + house
 * @param {string} sign - Zodiac sign
 * @param {number} house - House number (1-12)
 * @returns {string} Mythic chamber title
 */
export function getSaturnMythicTitle(sign, house) {
  const key = `${sign}_${house}`;
  return SATURN_MYTHIC_SKIN[key] || "The Stone Gate";
}

