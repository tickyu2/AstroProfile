/**
 * Get interpretation for any number type
 */
export function getInterpretation(type, number) {
  switch (type) {
    case 'lifePath':
    case 'destiny':
      return lifePathInterpretations[number] || lifePathInterpretations[reduceToSingleDigit(number)];
    case 'soulUrge':
      return soulUrgeInterpretations[number] || soulUrgeInterpretations[reduceToSingleDigit(number)];
    case 'personality':
      return personalityInterpretations[number] || personalityInterpretations[reduceToSingleDigit(number)];
    case 'personalYear':
      return personalYearGuidance[number] || personalYearGuidance[reduceToSingleDigit(number)];
    default:
      return null;
  }
}

/**
 * Reduce to single digit (preserving master numbers)
 */
function reduceToSingleDigit(num) {
  while (num > 9 && num !== 11 && num !== 22 && num !== 33) {
    num = num.toString().split('').reduce((a, b) => parseInt(a) + parseInt(b), 0);
  }
  return num;
}

