/**
 * Get the Sabian Symbol for a given sign and degree.
 * @param {string} sign - Full sign name (e.g., "Aries", "Taurus")
 * @param {number} degree - Degree within sign (0-29.99). Floors to integer.
 * @returns {{ degree: number, symbol: string, keynote: string } | null}
 */
export function getSabianSymbol(sign, degree) {
  const degreeInt = Math.floor(degree) % 30;
  const symbols = SABIAN_SYMBOLS[sign];
  if (!symbols || !symbols[degreeInt]) return null;
  const keynotes = SABIAN_KEYNOTES[sign];
  return { degree: degreeInt, symbol: symbols[degreeInt], keynote: keynotes?.[degreeInt] || '' };
}

/**
 * Collect Sabian Symbols for all planets and angles.
 * @param {Object} pObj - Planet data object (key -> { sign, degree, ... })
 * @param {Array} angles - Angles array [{ tag, sign, degree, lon }, ...]
 * @param {Object} PLANET_SYM - Symbol map
 * @param {Object} PLANET_NAME - Name map
 * @returns {Array} Array of { key, name, glyph, sign, degree, sabian, keynote }
 */
export function findAllSabianSymbols(pObj, angles, PLANET_SYM, PLANET_NAME) {
  const hits = [];

  // Planets
  for (const [key, data] of Object.entries(pObj)) {
    if (!data?.sign) continue;
    const deg = data.degree ?? data.degreeInSign ?? 0;
    const sabian = getSabianSymbol(data.sign, deg);
    if (sabian) {
      hits.push({
        key,
        name: PLANET_NAME[key] || key,
        glyph: PLANET_SYM[key] || '?',
        sign: data.sign,
        degree: deg,
        sabian: sabian.symbol,
        keynote: sabian.keynote,
      });
    }
  }

  // Angles (ASC, MC, DSC, IC)
  for (const a of angles) {
    const sabian = getSabianSymbol(a.sign, a.degree);
    if (sabian) {
      hits.push({
        key: `angle_${a.tag}`,
        name: a.tag,
        glyph: a.tag,
        sign: a.sign,
        degree: a.degree,
        sabian: sabian.symbol,
        keynote: sabian.keynote,
      });
    }
  }

  return hits;
}
