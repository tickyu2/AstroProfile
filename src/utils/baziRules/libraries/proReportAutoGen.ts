// ==================== EDITING OPERATIONS ====================

/**
 * Edit a section's content
 */
export function editSection(
  report: AutoGeneratedReport,
  sectionId: string,
  newContent: string,
  language: 'en' | 'zh' = 'en'
): AutoGeneratedReport {
  return {
    ...report,
    sections: report.sections.map(s => {
      if (s.id !== sectionId) return s;

      if (language === 'zh') {
        return {
          ...s,
          isEdited: true,
          editedContentZh: newContent
        };
      }

      return {
        ...s,
        isEdited: true,
        editedContent: newContent
      };
    })
  };
}

/**
 * Revert section to original content
 */
export function revertSection(
  report: AutoGeneratedReport,
  sectionId: string
): AutoGeneratedReport {
  return {
    ...report,
    sections: report.sections.map(s => {
      if (s.id !== sectionId) return s;
      return {
        ...s,
        isEdited: false,
        editedContent: undefined,
        editedContentZh: undefined
      };
    })
  };
}

/**
 * Reorder sections
 */
export function reorderAutoGenSections(
  report: AutoGeneratedReport,
  newOrder: string[]
): AutoGeneratedReport {
  const reorderedSections = newOrder
    .map((id, index) => {
      const section = report.sections.find(s => s.id === id);
      if (!section) return null;
      return { ...section, order: index + 1 };
    })
    .filter(Boolean) as AutoGeneratedSection[];

  return {
    ...report,
    layout: newOrder,
    sections: reorderedSections
  };
}

/**
 * Toggle section enabled/disabled
 */
export function toggleAutoGenSection(
  report: AutoGeneratedReport,
  sectionId: string
): AutoGeneratedReport {
  const section = report.sections.find(s => s.id === sectionId);

  if (section) {
    // Remove section
    return {
      ...report,
      layout: report.layout.filter(id => id !== sectionId),
      sections: report.sections.filter(s => s.id !== sectionId)
    };
  }

  // Section not in report - would need to regenerate to add
  return report;
}

/**
 * Change report tone
 */
export function changeTone(
  report: AutoGeneratedReport,
  newTone: TonePreset,
  ctx: ReportContext2
): AutoGeneratedReport {
  // Regenerate with new tone but preserve edits
  const newReport = autoGenerateReport(ctx, {
    language: report.language,
    forceTone: newTone
  });

  // Preserve edited sections
  return {
    ...newReport,
    sections: newReport.sections.map(newSection => {
      const oldSection = report.sections.find(s => s.id === newSection.id);
      if (oldSection?.isEdited) {
        return {
          ...newSection,
          isEdited: true,
          editedContent: oldSection.editedContent,
          editedContentZh: oldSection.editedContentZh
        };
      }
      return newSection;
    })
  };
}

// ==================== RENDERING ====================

/**
 * Render final report content
 */
export function renderAutoGenReport(
  report: AutoGeneratedReport,
  options: { includeRationale?: boolean } = {}
): string {
  const lang = report.language;

  let output = '';

  // Header
  output += `# BaZi Pro Report\n\n`;
  output += `*Generated: ${report.generatedAt.toLocaleDateString()}*\n`;
  output += `*Tone: ${TONE_PRESETS[report.tone].name}*\n`;
  output += `*Confidence: ${(report.confidence * 100).toFixed(0)}%*\n\n`;

  // Focus Areas
  if (report.focusAreas.length > 0) {
    output += `## Key Focus Areas\n\n`;
    const areas = lang === 'zh' ? report.focusAreasZh : report.focusAreas;
    areas.forEach(area => {
      output += `- ${area}\n`;
    });
    output += '\n';
  }

  // Sections
  for (const section of report.sections.sort((a, b) => a.order - b.order)) {
    const content = section.isEdited
      ? (lang === 'zh' ? section.editedContentZh || section.contentZh : section.editedContent || section.content)
      : (lang === 'zh' ? section.contentZh : section.content);

    output += `${content}\n\n`;

    if (options.includeRationale) {
      const rationale = lang === 'zh' ? section.rationaleZh : section.rationale;
      output += `> *Why this section: ${rationale}*\n\n`;
    }

    output += `---\n\n`;
  }

  // Global Rationale
  if (options.includeRationale && report.globalRationale.length > 0) {
    output += `## AI Reasoning\n\n`;
    const rationale = lang === 'zh' ? report.globalRationaleZh : report.globalRationale;
    rationale.forEach(r => {
      output += `- ${r}\n`;
    });
  }

  return output;
}

/**
 * Export report as JSON
 */
export function exportAutoGenReportJson(report: AutoGeneratedReport): string {
  return JSON.stringify(report, null, 2);
}

/**
 * Get section for editing UI
 */
export function getSectionForEditing(
  report: AutoGeneratedReport,
  sectionId: string
): AutoGeneratedSection | undefined {
  return report.sections.find(s => s.id === sectionId);
}

/**
 * Get all editable sections
 */
export function getEditableSections(report: AutoGeneratedReport): Array<{
  id: string;
  label: string;
  content: string;
  rationale: string;
  isEdited: boolean;
  order: number;
}> {
  const lang = report.language;

  return report.sections
    .sort((a, b) => a.order - b.order)
    .map(s => ({
      id: s.id,
      label: lang === 'zh' ? s.labelZh : s.label,
      content: s.isEdited
        ? (lang === 'zh' ? s.editedContentZh || s.contentZh : s.editedContent || s.content)
        : (lang === 'zh' ? s.contentZh : s.content),
      rationale: lang === 'zh' ? s.rationaleZh : s.rationale,
      isEdited: s.isEdited,
      order: s.order
    }));
}

// ==================== QUICK AUTO-GEN ====================

/**
 * Quick auto-generate for common use cases
 */
export function quickAutoGenReport(
  ctx: ReportContext2,
  preset: 'comprehensive' | 'timing' | 'personality' | 'guidance' = 'comprehensive'
): AutoGeneratedReport {
  const presetOptions: Record<string, AutoGenOptions> = {
    comprehensive: { maxSections: 8 },
    timing: { maxSections: 4, forceTone: 'professional' },
    personality: { maxSections: 5, forceTone: 'poetic' },
    guidance: { maxSections: 3, forceTone: 'coaching' }
  };

  return autoGenerateReport(ctx, presetOptions[preset]);
}

