import {
  buildProReportSections2,
  type ReportSection2,
  type ReportContext2
} from './proReportDesigner2';

import {
  suggestLayout,
  type LayoutSuggestion,
  type LayoutContext
} from './layoutSuggestionEngine';

import {
  TONE_PRESETS,
  getTonePreset,
  applyTone,
  applyToneToHeader,
  type TonePreset
} from './tonePresets';

// ==================== TYPES ====================

export interface AutoGeneratedSection {
  id: string;
  label: string;
  labelZh: string;
  content: string;
  contentZh: string;
  rationale: string;
  rationaleZh: string;
  isEmphasized: boolean;
  isEdited: boolean;
  editedContent?: string;
  editedContentZh?: string;
  order: number;
}

export interface AutoGeneratedReport {
  tone: TonePreset;
  layout: string[];
  sections: AutoGeneratedSection[];
  globalRationale: string[];
  globalRationaleZh: string[];
  focusAreas: string[];
  focusAreasZh: string[];
  confidence: number;
  generatedAt: Date;
  language: 'en' | 'zh';
}

export interface AutoGenOptions {
  language?: 'en' | 'zh';
  forceTone?: TonePreset;
  includeExtended?: boolean;
  maxSections?: number;
}

// ==================== AUTO-GENERATION ENGINE ====================

/**
 * Auto-generate complete report with rationale
 */
export function autoGenerateReport(
  ctx: ReportContext2,
  options: AutoGenOptions = {}
): AutoGeneratedReport {
  const language = options.language || 'en';

  // Build layout context
  const layoutContext: LayoutContext = {
    ctx,
    userPreferences: {
      wantsTiming: true,
      wantsNarrative: options.includeExtended,
      wantsGuidance: true
    }
  };

  // Get AI layout suggestions
  const suggestion = suggestLayout(layoutContext);

  // Determine tone (user override or AI suggestion)
  const tone = options.forceTone || suggestion.recommendedTone;
  const style = getTonePreset(tone);

  // Build base sections
  const baseSections = buildProReportSections2(ctx);

  // Generate sections with content and rationale
  const sections: AutoGeneratedSection[] = suggestion.recommendedOrder
    .slice(0, options.maxSections || 10)
    .map((id, index) => {
      const section = baseSections.find(s => s.id === id);
      if (!section) return null;

      const isEmphasized = suggestion.emphasize.includes(id);
      const sectionRationale = getSectionRationale(id, suggestion, ctx);

      // Generate content with tone applied
      const rawContent = section.renderer(ctx);
      const rawContentZh = section.rendererZh(ctx);

      const content = applyTone(
        applyToneToHeader(section.label, tone, 'en') + '\n\n' +
        rawContent.replace(/^###?\s+[^\n]+\n/, ''),
        tone,
        'en'
      );

      const contentZh = applyTone(
        applyToneToHeader(section.labelZh, tone, 'zh') + '\n\n' +
        rawContentZh.replace(/^###?\s+[^\n]+\n/, ''),
        tone,
        'zh'
      );

      return {
        id,
        label: section.label,
        labelZh: section.labelZh,
        content,
        contentZh,
        rationale: sectionRationale.en,
        rationaleZh: sectionRationale.zh,
        isEmphasized,
        isEdited: false,
        order: index + 1
      };
    })
    .filter(Boolean) as AutoGeneratedSection[];

  return {
    tone,
    layout: suggestion.recommendedOrder,
    sections,
    globalRationale: suggestion.rationale,
    globalRationaleZh: suggestion.rationaleZh,
    focusAreas: suggestion.focusAreas,
    focusAreasZh: suggestion.focusAreasZh,
    confidence: suggestion.confidence,
    generatedAt: new Date(),
    language
  };
}

