/**
 * Analyze the stem-branch relationship for a single pillar
 *
 * @param stem - Heavenly Stem character (e.g., "甲")
 * @param branch - Earthly Branch character (e.g., "寅")
 * @param pillarName - Name of the pillar (year, month, day, hour)
 * @returns StemBranchRelation with detailed analysis
 */
export function computeStemBranchRelation(
  stem: string,
  branch: string,
  pillarName: string = 'pillar'
): StemBranchRelation {
  const stemElement = STEM_ELEMENT[stem] || 'wood';
  const branchMainElement = BRANCH_MAIN_ELEMENT[branch] || 'wood';
  const hiddenStems = BRANCH_HIDDEN_STEMS[branch] || [];
  const hiddenElements = hiddenStems.map(s => STEM_ELEMENT[s] || 'wood');

  // Check for root (stem's element in hidden stems)
  const hasRoot = hiddenElements.includes(stemElement);
  let rootStrength = 0;

  if (hasRoot) {
    // Position matters: Main Qi (index 0) is strongest
    const rootIndex = hiddenElements.indexOf(stemElement);
    rootStrength = rootIndex === 0 ? 1.0 : (rootIndex === 1 ? 0.6 : 0.3);
  }

  // Determine relationship type and strength modifier
  let relation: RelationType;
  let strengthModifier: number;

  if (stemElement === branchMainElement || hasRoot) {
    // Same element or rooted = strong support
    relation = 'rooted';
    strengthModifier = 1.0 + (rootStrength * 0.3); // 1.0 to 1.3
  } else if (GENERATED_BY[stemElement] === branchMainElement) {
    // Branch generates stem = support
    relation = 'supported';
    strengthModifier = 1.1;
  } else if (GENERATES[stemElement] === branchMainElement) {
    // Stem generates branch = drained
    relation = 'drained';
    strengthModifier = 0.9;
  } else if (CONTROLLED_BY[stemElement] === branchMainElement) {
    // Branch controls stem = weakened
    relation = 'controlled';
    strengthModifier = 0.8;
  } else if (CONTROLS[stemElement] === branchMainElement) {
    // Stem controls branch = exhausting effort
    relation = 'exhausting';
    strengthModifier = 0.85;
  } else {
    relation = 'neutral';
    strengthModifier = 1.0;
  }

  const explanation = generateRelationExplanation(
    pillarName,
    stem,
    stemElement,
    branch,
    branchMainElement,
    relation,
    hasRoot,
    rootStrength
  );

  return {
    pillarName,
    stem,
    stemElement,
    branch,
    branchMainElement,
    hiddenStems,
    hiddenElements,
    relation,
    strengthModifier,
    hasRoot,
    rootStrength,
    explanation
  };
}

/**
 * Analyze stem-branch relations for all four pillars
 *
 * @param pillars - Four Pillars with stem and branch for each
 * @returns ChartStemBranchAnalysis with comprehensive analysis
 */
export function computeChartStemBranchRelations(
  pillars: FourPillars
): ChartStemBranchAnalysis {
  const pillarKeys = ['year', 'month', 'day', 'hour'] as const;

  const pillarRelations = pillarKeys.map(key =>
    computeStemBranchRelation(pillars[key].stem, pillars[key].branch, key)
  );

  // Extract day master relation
  const dayMasterRelation = pillarRelations.find(p => p.pillarName === 'day')!;

  // Count rooted pillars
  const rootedPillarCount = pillarRelations.filter(p => p.hasRoot).length;

  // Calculate overall rootedness (weighted average)
  const pillarWeights = { year: 0.15, month: 0.25, day: 0.40, hour: 0.20 };
  let overallRootedness = 0;

  pillarRelations.forEach(p => {
    const weight = pillarWeights[p.pillarName as keyof typeof pillarWeights] || 0.25;
    overallRootedness += p.rootStrength * weight;
  });

  // Normalize to 0-1
  overallRootedness = Math.min(1, overallRootedness);

  // Find strongest support and weakest link
  const sorted = [...pillarRelations].sort((a, b) => b.strengthModifier - a.strengthModifier);
  const strongestSupport = sorted[0].pillarName;
  const weakestLink = sorted[sorted.length - 1].pillarName;

  // Is Day Master well-rooted?
  const dmHasStrongRoot = dayMasterRelation.hasRoot && dayMasterRelation.rootStrength >= 0.6;

  const explanation = generateChartExplanation(
    pillarRelations,
    dayMasterRelation,
    overallRootedness,
    rootedPillarCount,
    dmHasStrongRoot
  );

  return {
    pillars: pillarRelations,
    dayMasterRelation,
    overallRootedness,
    rootedPillarCount,
    strongestSupport,
    weakestLink,
    dmHasStrongRoot,
    explanation
  };
}

