/**
 * ============================================================================
 * BAZI STEM-BRANCH RELATIONS ENGINE
 * ============================================================================
 *
 * Analyzes the relationship between the Heavenly Stem and Earthly Branch
 * within each pillar of the BaZi chart.
 *
 * Classical Doctrine:
 * The stem "sits" on the branch. The relationship between them determines:
 * - Rootedness: Is the stem supported by its branch?
 * - Transparency: Is the stem's energy clearly expressed?
 * - Strength: How much power does the stem receive?
 *
 * Key Relationships:
 * 1. SAME ELEMENT (通根 Tong Gen) - Stem rooted in branch = strong support
 * 2. GENERATED BY (得生 De Sheng) - Branch element generates stem = support
 * 3. GENERATES BRANCH (泄气 Xie Qi) - Stem generates branch = draining
 * 4. CONTROLLED BY (被克 Bei Ke) - Branch element controls stem = weakening
 * 5. CONTROLS BRANCH (克制 Ke Zhi) - Stem controls branch = exhausting
 *
 * Created: January 2026
 * Based on: Classical BaZi stem-branch relationship doctrine
 * ============================================================================
 */

