// ============================================================================
// TYPES
// ============================================================================

export type RelationType =
  | 'rooted'       // Same element - strong support
  | 'supported'    // Branch generates stem - moderate support
  | 'drained'      // Stem generates branch - mild weakening
  | 'controlled'   // Branch controls stem - weakening
  | 'exhausting'   // Stem controls branch - mild exhausting
  | 'neutral';     // No direct relationship

export interface StemBranchRelation {
  pillarName: string;
  stem: string;
  stemElement: Element;
  branch: string;
  branchMainElement: Element;
  hiddenStems: string[];
  hiddenElements: Element[];
  relation: RelationType;
  strengthModifier: number;  // 0.7 - 1.3 range
  hasRoot: boolean;          // Is stem's element found in branch's hidden stems?
  rootStrength: number;      // 0 if no root, 0.3-1.0 based on position in hidden
  explanation: string;
}

export interface ChartStemBranchAnalysis {
  pillars: StemBranchRelation[];
  dayMasterRelation: StemBranchRelation;
  overallRootedness: number;        // 0-1 scale
  rootedPillarCount: number;        // How many pillars have the stem rooted
  strongestSupport: string;         // Which pillar provides strongest support
  weakestLink: string;              // Which pillar is most challenged
  dmHasStrongRoot: boolean;         // Is Day Master well-rooted?
  explanation: string;
}

export interface FourPillars {
  year: { stem: string; branch: string };
  month: { stem: string; branch: string };
  day: { stem: string; branch: string };
  hour: { stem: string; branch: string };
}

