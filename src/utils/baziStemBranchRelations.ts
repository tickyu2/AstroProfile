function generateRelationExplanation(
  pillarName: string,
  stem: string,
  stemElement: Element,
  branch: string,
  branchMainElement: Element,
  relation: RelationType,
  hasRoot: boolean,
  rootStrength: number
): string {
  const stemName = capitalize(stemElement);
  const branchName = capitalize(branchMainElement);
  const pillarTitle = capitalize(pillarName);

  let explanation = `${pillarTitle} Pillar: ${stem} ${stemName} on ${branch} ${branchName}\n\n`;

  const relationMessages: Record<RelationType, string> = {
    rooted: `The ${stemName} stem finds its root in the ${branch} branch. This is excellent support - like a tree with deep roots.`,
    supported: `The ${branchName} branch generates ${stemName}. The stem receives nourishing support from below.`,
    drained: `The ${stemName} stem generates the ${branchName} branch. Energy flows outward - productive but slightly draining.`,
    controlled: `The ${branchName} branch controls ${stemName}. The stem faces pressure from its foundation.`,
    exhausting: `The ${stemName} stem controls the ${branchName} branch. Dominance requires constant effort.`,
    neutral: `The ${stemName} stem and ${branchName} branch have no direct elemental relationship.`
  };

  explanation += relationMessages[relation];

  if (hasRoot) {
    const strengthLabel = rootStrength >= 0.8 ? 'main qi' : (rootStrength >= 0.5 ? 'middle qi' : 'residual qi');
    explanation += `\n\nRoot found in branch's ${strengthLabel} (strength: ${(rootStrength * 100).toFixed(0)}%).`;
  }

  return explanation;
}

function generateChartExplanation(
  pillarRelations: StemBranchRelation[],
  dayMasterRelation: StemBranchRelation,
  overallRootedness: number,
  rootedPillarCount: number,
  dmHasStrongRoot: boolean
): string {
  let explanation = `Chart Stem-Branch Analysis\n${'='.repeat(30)}\n\n`;

  // Summary stats
  explanation += `Rooted Pillars: ${rootedPillarCount}/4\n`;
  explanation += `Overall Rootedness: ${(overallRootedness * 100).toFixed(0)}%\n\n`;

  // Day Master focus
  explanation += `Day Master (${dayMasterRelation.stem} ${capitalize(dayMasterRelation.stemElement)}):\n`;

  if (dmHasStrongRoot) {
    explanation += `Well-rooted in the ${dayMasterRelation.branch} branch. `;
    explanation += `Your core self has a strong foundation and clear expression.\n\n`;
  } else if (dayMasterRelation.hasRoot) {
    explanation += `Has moderate root in the ${dayMasterRelation.branch} branch. `;
    explanation += `Your foundation is present but could use strengthening.\n\n`;
  } else {
    explanation += `Not rooted in the ${dayMasterRelation.branch} branch. `;
    explanation += `Your Day Master must draw strength from other pillars or luck cycles.\n\n`;
  }

  // Pillar summary
  explanation += `Pillar Relations:\n`;
  pillarRelations.forEach(p => {
    const icon = p.hasRoot ? ' (rooted)' : '';
    explanation += `- ${capitalize(p.pillarName)}: ${p.relation}${icon}\n`;
  });

  // Classical interpretation
  explanation += `\nClassical Interpretation:\n`;
  if (overallRootedness >= 0.7) {
    explanation += `Strong overall rootedness indicates a chart where stems express themselves clearly and receive good support from their branches.`;
  } else if (overallRootedness >= 0.4) {
    explanation += `Moderate rootedness - some stems have support while others must work harder. This creates an interesting dynamic of strengths and growth areas.`;
  } else {
    explanation += `Limited rootedness means the stems often work without strong foundational support. This can indicate adaptability but also the need for external support from luck cycles.`;
  }

  return explanation;
}

function capitalize(str: string): string {
  return str.charAt(0).toUpperCase() + str.slice(1);
}

