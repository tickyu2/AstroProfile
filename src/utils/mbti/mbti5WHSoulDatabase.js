/**
 * Get 5W+H+Soul analysis for a pairing
 */
export function get5WHSoulAnalysis(type1, type2) {
  const pair = [type1, type2].sort().join('-');
  return MBTI_5WH_SOUL_DATABASE[pair] || null;
}

/**
 * Check if detailed 5W+H+Soul content exists
 */
export function has5WHSoulContent(type1, type2) {
  const pair = [type1, type2].sort().join('-');
  return MBTI_5WH_SOUL_DATABASE.hasOwnProperty(pair);
}

/**
 * Get list of all available pairing analyses
 */
export function getAvailablePairings() {
  return Object.keys(MBTI_5WH_SOUL_DATABASE);
}
