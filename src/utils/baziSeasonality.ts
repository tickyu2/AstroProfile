/**
 * Get rooting seasonal weights (underground Qi availability).
 * Used for M1 rooting tier calculation only.
 */
export function getRootingSeasonalWeights(monthBranch: string): Record<Element, number> {
  if (ROOTING_BRANCH_WEIGHTS[monthBranch]) {
    return ROOTING_BRANCH_WEIGHTS[monthBranch];
  }
  console.warn(`Unknown month branch for rooting: ${monthBranch}`);
  return { wood: 1.0, fire: 1.0, earth: 1.0, metal: 1.0, water: 1.0 };
}

/**
 * Get surface seasonal weights (expressive Qi).
 * Handles both regular seasons and Earth transition months.
 */
export function getSeasonalWeights(monthBranch: string): Record<Element, number> {
  // Use exact per-branch lookup (covers all 12 months including Earth pivots)
  if (BRANCH_WEIGHTS[monthBranch]) {
    return BRANCH_WEIGHTS[monthBranch];
  }

  // Fallback: standard season lookup for any non-branch key
  const season = SEASON_MAP[monthBranch];
  if (!season) {
    console.warn(`Unknown month branch: ${monthBranch}`);
    return { wood: 1.0, fire: 1.0, earth: 1.0, metal: 1.0, water: 1.0 };
  }

  if (!season.startsWith("earth_transition")) {
    return SEASON_WEIGHTS[season];
  }

  // Legacy fallback for Earth transitions (should not reach here)
  const transition = EARTH_TRANSITION_MAP[monthBranch];
  if (!transition) {
    return { wood: 1.0, fire: 1.0, earth: 1.0, metal: 1.0, water: 1.0 };
  }
  const { incoming, outgoing } = transition;
  const weights: Record<Element, number> = {
    earth: 1.20, wood: 0.70, fire: 0.70, metal: 0.70, water: 0.70
  };
  weights[incoming] = 0.90;
  weights[outgoing] = 0.80;
  return weights;
}

/**
 * Get season information for display
 */
export function getSeasonInfo(monthBranch: string): { name: string; chinese: string; emoji: string } {
  const season = SEASON_MAP[monthBranch];
  return SEASON_INFO[season] || { name: "Unknown", chinese: "?", emoji: "❓" };
}

/**
 * Get the dominant element from a distribution
 */
function getDominantElement(distribution: Record<Element, number>): Element {
  let maxElement: Element = "wood";
  let maxValue = -1;

  for (const [element, value] of Object.entries(distribution)) {
    if (value > maxValue) {
      maxValue = value;
      maxElement = element as Element;
    }
  }

  return maxElement;
}

/**
 * Apply seasonality adjustment to raw element distribution
 *
 * Formula:
 *   adjusted[element] = raw[element] * seasonal_weight[element]
 *   normalized[element] = adjusted[element] / sum(adjusted)
 *
 * @param raw - Raw element distribution (from stems + hidden stems)
 * @param monthBranch - Month Branch character (e.g., "寅", "卯", "辰")
 * @returns SeasonalityResult with weights, adjusted, normalized values
 */
export function applySeasonality(
  raw: Record<Element, number>,
  monthBranch: string
): SeasonalityResult {
  const weights = getSeasonalWeights(monthBranch);
  const seasonInfo = getSeasonInfo(monthBranch);
  const season = SEASON_MAP[monthBranch] || "unknown";

  // Normalize raw to percentages first
  const rawTotal = Object.values(raw).reduce((a, b) => a + b, 0);
  const rawNormalized: Record<Element, number> = {
    wood: rawTotal > 0 ? (raw.wood / rawTotal) * 100 : 20,
    fire: rawTotal > 0 ? (raw.fire / rawTotal) * 100 : 20,
    earth: rawTotal > 0 ? (raw.earth / rawTotal) * 100 : 20,
    metal: rawTotal > 0 ? (raw.metal / rawTotal) * 100 : 20,
    water: rawTotal > 0 ? (raw.water / rawTotal) * 100 : 20
  };

  // Apply weights to raw distribution
  const adjusted: Record<Element, number> = {
    wood: raw.wood * weights.wood,
    fire: raw.fire * weights.fire,
    earth: raw.earth * weights.earth,
    metal: raw.metal * weights.metal,
    water: raw.water * weights.water
  };

  // Calculate total for normalization
  const adjustedTotal = Object.values(adjusted).reduce((a, b) => a + b, 0);

  // Normalize adjusted to percentages (0-100)
  const adjustedNormalized: Record<Element, number> = {
    wood: adjustedTotal > 0 ? (adjusted.wood / adjustedTotal) * 100 : 0,
    fire: adjustedTotal > 0 ? (adjusted.fire / adjustedTotal) * 100 : 0,
    earth: adjustedTotal > 0 ? (adjusted.earth / adjustedTotal) * 100 : 0,
    metal: adjustedTotal > 0 ? (adjusted.metal / adjustedTotal) * 100 : 0,
    water: adjustedTotal > 0 ? (adjusted.water / adjustedTotal) * 100 : 0
  };

  // Calculate deltas (change in percentage points)
  const deltas: Record<Element, number> = {
    wood: adjustedNormalized.wood - rawNormalized.wood,
    fire: adjustedNormalized.fire - rawNormalized.fire,
    earth: adjustedNormalized.earth - rawNormalized.earth,
    metal: adjustedNormalized.metal - rawNormalized.metal,
    water: adjustedNormalized.water - rawNormalized.water
  };

  // Determine dominant elements
  const dominantBefore = getDominantElement(raw);
  const dominantAfter = getDominantElement(adjustedNormalized);

  // Generate explanation
  const explanation = generateExplanation(
    monthBranch,
    season,
    weights,
    dominantBefore,
    dominantAfter
  );

  return {
    season,
    seasonChinese: seasonInfo.chinese,
    seasonEmoji: seasonInfo.emoji,
    monthBranch,
    weights,
    raw,
    rawNormalized,
    adjusted,
    normalized: adjustedNormalized,  // Backwards compatibility
    adjustedNormalized,
    deltas,
    dominantBefore,
    dominantAfter,
    dominantChanged: dominantBefore !== dominantAfter,
    explanation
  };
}

/**
 * Generate educational explanation of the seasonality adjustment
 */
function generateExplanation(
  monthBranch: string,
  season: string,
  weights: Record<Element, number>,
  dominantBefore: Element,
  dominantAfter: Element
): string {
  const seasonInfo = getSeasonInfo(monthBranch);
  const isEarthTransition = season.startsWith("earth_transition");

  let explanation = `Born in ${seasonInfo.name} (${monthBranch} month), `;

  if (isEarthTransition) {
    const transition = EARTH_TRANSITION_MAP[monthBranch];
    if (transition) {
      explanation += `an Earth transition month. Earth (土) becomes dominant during this period, `;
      explanation += `with ${capitalize(transition.incoming)} strengthening (incoming season) `;
      explanation += `and ${capitalize(transition.outgoing)} weakening (outgoing season). `;
    }
  } else {
    const dominant = Object.entries(weights).find(([_, w]) => w === 1.0)?.[0] || "unknown";
    explanation += `when ${capitalize(dominant)} naturally thrives. `;
  }

  if (dominantBefore !== dominantAfter) {
    explanation += `This shifts your dominant element from ${capitalize(dominantBefore)} to ${capitalize(dominantAfter)}.`;
  } else {
    explanation += `Your dominant element ${capitalize(dominantAfter)} is strengthened by the season.`;
  }

  return explanation;
}

function capitalize(str: string): string {
  return str.charAt(0).toUpperCase() + str.slice(1);
}

