/**
 * Calculate the impact of seasonality on each element
 * Returns positive values for elements that gained strength,
 * negative for elements that weakened
 */
export function calculateSeasonalImpact(
  raw: Record<Element, number>,
  normalized: Record<Element, number>
): Record<Element, number> {
  // First normalize raw to percentages for fair comparison
  const rawTotal = Object.values(raw).reduce((a, b) => a + b, 0);

  return {
    wood: normalized.wood - (raw.wood / rawTotal * 100),
    fire: normalized.fire - (raw.fire / rawTotal * 100),
    earth: normalized.earth - (raw.earth / rawTotal * 100),
    metal: normalized.metal - (raw.metal / rawTotal * 100),
    water: normalized.water - (raw.water / rawTotal * 100)
  };
}

/**
 * Get elements that gained/lost strength due to seasonality
 */
export function getSeasonalGainersLosers(impact: Record<Element, number>): {
  gainers: Array<{ element: Element; change: number }>;
  losers: Array<{ element: Element; change: number }>;
} {
  const entries = Object.entries(impact) as Array<[Element, number]>;

  const gainers = entries
    .filter(([_, change]) => change > 0.5) // Threshold for significance
    .map(([element, change]) => ({ element, change }))
    .sort((a, b) => b.change - a.change);

  const losers = entries
    .filter(([_, change]) => change < -0.5)
    .map(([element, change]) => ({ element, change }))
    .sort((a, b) => a.change - b.change);

  return { gainers, losers };
}

